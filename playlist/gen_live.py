#!/usr/bin/env python3
"""生成高配盒子的 TiviMate 直播节目源 m3u。

步骤（规则与 iptv-tivimate 仓库一致）：
  1. 拉取 zseagate/hypnotix 最新直播播放列表（codeload 免 github TLS 拦截）；
  2. 按优先级合并 + 按 URL 去重；
  3. 用仓库分组/排列规则（merge_rules: classify_group + sort_final）重分类为中文字段并排序；
  4. 写出 m3u（默认 stdout，或 -o 指定文件）。

用法:
  python3 gen_live.py -o /sdcard/iptv.m3u          # 输出到指定文件
  python3 gen_live.py > iptv.m3u                   # 输出到 stdout
  python3 gen_live.py --repo /path/to/hypnotix     # 用本地 hypnotix 快照(离线/调试)

环境变量:
  HYPNOTIX_TARBALL  覆盖 tarball URL（默认 codeload hypnotix main）
"""
from __future__ import annotations

import argparse
import io
import os
import re
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import merge_rules as rules

TARBALL = os.environ.get(
    "HYPNOTIX_TARBALL",
    "https://codeload.github.com/zseagate/hypnotix/tar.gz/refs/heads/main",
)
ARCHIVE_ROOT = "hypnotix-main"

# 优先级(先出现者胜)：源标签按仓库规则语义选择
#   freetv(国际公共频道) -> iptv-org-ent  -> 归"海外频道·地区"
#   其它 -> 关键字规则(新闻/电影/体育/港澳台/央视/中文字段保留)
PRESETS = [
    ("iptv-org-ent",    "playlists/freetv.m3u"),
    ("hypnotix-news",   "playlist.m3u"),
    ("hypnotix-news2",  "playlists/news.m3u"),
    ("hypnotix-news3",  "playlists/fnos_news_hls.m3u"),
    ("hypnotix-cn",     "playlists/iptvorgcn.m3u"),
    ("hypnotix-hk",     "playlists/iptvorghk.m3u"),
    ("hypnotix-tw",     "playlists/iptvorgtw.m3u"),
    ("hypnotix-zh",     "playlists/iptvorgzh.m3u"),
    ("hypnotix-sports", "playlists/iptvorgsports.m3u"),
    ("hypnotix-movies", "playlists/iptvorgmovies.m3u"),
]


def parse_m3u(text: str) -> list[dict]:
    """简易 m3u 解析: 返回 [{extinf,url}]。"""
    out, cur = [], None
    for raw in text.splitlines():
        s = raw.strip()
        if s.startswith("#EXTINF"):
            cur = s
        elif s and not s.startswith("#") and cur:
            out.append({"extinf": cur, "url": s})
            cur = None
    return out


def channel_name(extinf: str) -> str:
    return extinf.rsplit(",", 1)[-1].strip() if "," in extinf else extinf


def fetch_tarball() -> bytes:
    req = urllib.request.Request(TARBALL, headers={"User-Agent": "iptv-tvbox-highend"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def collect_from_repo(root: Path) -> list[dict]:
    """从 hypnotix 仓库目录收集全部直播条目(合并+URL去重+source标签)。"""
    seen, entries = set(), []
    for label, rel in PRESETS:
        f = root / rel
        if not f.exists():
            print(f"[warn] skip missing: {rel}", file=sys.stderr)
            continue
        for e in parse_m3u(f.read_text(encoding="utf-8", errors="ignore")):
            if e["url"] not in seen:
                seen.add(e["url"])
                e["source"] = label
                e["name"] = channel_name(e["extinf"])
                entries.append(e)
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--output", help="输出 m3u 路径(缺省 stdout)")
    ap.add_argument("--repo", help="使用本地 hypnotix 仓库目录(不联网拉取)")
    args = ap.parse_args()

    if args.repo:
        entries = collect_from_repo(Path(args.repo))
    else:
        print(f"[gen] downloading {TARBALL}", file=sys.stderr)
        data = fetch_tarball()
        with tempfile.TemporaryDirectory() as td:
            with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tf:
                tf.extractall(td)  # noqa: S202  (来源固定为仓库快照)
            root = Path(td) / ARCHIVE_ROOT
            if not root.exists():
                print(f"[err] tarball root not found: {ARCHIVE_ROOT}", file=sys.stderr)
                return 1
            entries = collect_from_repo(root)

    if not entries:
        print("[err] no channels collected", file=sys.stderr)
        return 1

    # 仓库规则: 重分类分组 + 排序
    rules.reclassify(entries)
    entries = rules.sort_final(entries)

    lines = [
        "#EXTM3U",
        f"# Generated by gen_live.py {os.path.basename(__file__)} (rules: merge_rules)",
        f"# Channel-Count: {len(entries)}",
    ]
    for e in entries:
        lines.append(e["extinf"])
        lines.append(e["url"])
    text = "\n".join(lines) + "\n"

    groups: dict[str, int] = {}
    for e in entries:
        m = re.search(r'group-title="([^"]*)"', e["extinf"])
        g = m.group(1) if m else "其他频道"
        groups[g] = groups.get(g, 0) + 1

    print(f"[gen] channels={len(entries)} groups={len(groups)}", file=sys.stderr)
    for g, c in sorted(groups.items(), key=lambda x: -x[1]):
        print(f"  {c:5d}  {g}", file=sys.stderr)

    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"[gen] written: {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
